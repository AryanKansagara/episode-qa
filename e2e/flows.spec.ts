test('episode viewer: scrubber lowers to the start, keys step and override', async ({ page }) => {
  await newDataset(page)
  await importFiles(page, THREE)
  const ep = await openEpisode(page, 'B')
  const ring = ep.locator('.score-ring').first()
  await expect(ring).toHaveText('76')
  const slider = ep.getByRole('slider').first()
  await slider.focus()
  // Before 1.0 s nothing is missing yet, so the score so far is 100.
  await slider.press('Home')
  await expect(ring).toHaveText('100')
  await slider.press('End')
  await expect(ring).toHaveText('76')
  await page.locator('h1').click()
  await page.keyboard.press('x')
  await expect(ep.locator('h2 .badge').first()).toHaveText('Excluded')
  await expect(ep).toContainText('Manual exclude')
  await page.keyboard.press('a')
  await expect(ep.locator('h2 .badge').first()).toHaveText('Kept')
  await page.keyboard.press('u')
  await expect(ep).toContainText('No exclude rule matches')
  // Worst first: B (76), then A and C (100).
  await page.keyboard.press('j')
  await expect(page.locator('#ep-detail h2 .mono')).toHaveText('A')
  await page.keyboard.press('k')
  await expect(page.locator('#ep-detail h2 .mono')).toHaveText('B')
})

test('filters, tags and overrides survive a reload', async ({ page }) => {
  const base = await newDataset(page)
  await importFiles(page, THREE)
  const ep = await openEpisode(page, 'C')
  await ep.getByRole('button', { name: 'Always keep' }).click()
  await expect(ep.locator('h2 .badge').first()).toHaveText('Kept')
  await ep.getByLabel('Tags, comma separated').fill('Rig-1, clutter')
  await ep.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Tags saved')).toBeVisible()
  await closeEpisode(page)
  await page.reload()
  await page.getByLabel('Search id or tag').fill('rig-1')
  await expect(page.locator('.ep-table tbody tr')).toHaveCount(1)
  expect((await cells(page.locator('.ep-table'), 'C'))[6]).toBe('Keep manual')
  await page.getByLabel('Search id or tag').fill('nothing like this')
  await expect(page.getByText('No episodes match')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByLabel('Operator').selectOption('ben')
  await expect(page.locator('.ep-table tbody tr')).toHaveCount(1)
  const j = await curatedJson(page)
  expect(j.episodes.map(e => [e.episode_id, e.tags])).toEqual([['A', []], ['B', []], ['C', ['rig-1', 'clutter']]])
  await expect(panelOf(page, 'Manual overrides')).toContainText('C kept')
  await page.goto(`${base}/report`)
  await expect(page.getByText('Manual overrides: C (keep)')).toBeVisible()
})

test('rules: add, edit, disable, remove and undo change what is kept', async ({ page }) => {
  await newDataset(page)
  await importFiles(page, THREE)
  await openTab(page, 'Curate & export')
  await expect(kpi(page, 'Kept')).toHaveText('2')
  await page.getByRole('button', { name: 'Add rule' }).click()
  await expect(page.locator('.rule')).toHaveCount(6)
  const rule = page.locator('.rule').last()
  await rule.getByLabel('Value').fill('80')
  await rule.getByLabel('Value').press('Enter')
  await expect(rule.locator('.rule-hits')).toHaveText('1 match')
  await expect(kpi(page, 'Kept')).toHaveText('1')
  await page.locator('.rule').first().getByRole('checkbox').click()
  await expect(kpi(page, 'Kept')).toHaveText('2')
  await rule.getByLabel('Field').selectOption('operator')
  await rule.getByLabel('Value').fill('ANA')
  await rule.getByLabel('Value').press('Enter')
  await expect(kpi(page, 'Kept')).toHaveText('1')
  await page.reload()
  await expect(kpi(page, 'Kept')).toHaveText('1')
  await page.locator('.rule').last().getByRole('button', { name: /^Remove rule/ }).click()
  await expect(page.locator('.rule')).toHaveCount(5)
  await expect(kpi(page, 'Kept')).toHaveText('3')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.locator('.rule')).toHaveCount(6)
  await expect(kpi(page, 'Kept')).toHaveText('1')
})

test('thresholds re-run the checks; versions record the result and compare', async ({ page }) => {
  await newDataset(page)
  await importFiles(page, THREE)
  // A gap of 4 periods is not longer than 4.5, so B has no drops any more. The 0.4 rad step now counts as motion:
  // third differences 0.3, -0.6, 0.3 over 0.001 are 300, 600, 300 rad/s3, one spike, 4 points.
  await page.getByLabel(/^Drop gap/).fill('4.5')
  await openTab(page, 'Episodes')
  await expect.poll(async () => (await cells(page.locator('.ep-table'), 'B'))[3]).toBe('96')
  await page.getByRole('button', { name: 'Save version' }).click()
  await expect(page.getByText(/Saved “Version 2”: 2 of 3 episodes kept/)).toBeVisible()
  await openTab(page, 'History')
  // (100 + 76 + 100) / 3 = 92.0 before, (100 + 96 + 100) / 3 = 98.7 after.
  expect((await cells(page, 'Import three.csv'))[4]).toBe('92.0')
  expect((await cells(page, 'Version 2'))[4]).toBe('98.7')
  await expect(page.getByRole('heading', { name: 'Import three.csv → Version 2' })).toBeVisible()
  await expect(kpi(page, 'Mean score')).toHaveText('98.7')
  await expect(page.locator('.kpi', { hasText: 'Mean score' })).toContainText('+6.7')
  await expect(page.getByText('Dropped frames: 1 → 0')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('rowheader', { name: 'Version 2' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Version 2' }).click()
  await page.getByRole('button', { name: 'Delete version', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: 'Version 2' })).toHaveCount(0)
})

