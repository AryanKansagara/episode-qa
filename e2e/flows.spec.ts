test('datasets can be renamed, exported, cleared and deleted with undo', async ({ page }) => {
  const base = await newDataset(page)
  await importFiles(page, THREE)
  await page.getByRole('button', { name: 'Clear imported data' }).click()
  await page.getByRole('button', { name: 'Clear data' }).click()
  await expect(page.getByText('Start here.')).toBeVisible()
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(panelOf(page, 'Imported data')).toContainText('3 episodes on this device')

  await page.goto('/app')
  await page.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Dataset name').fill('Pilot run')
  await page.getByLabel('Dataset name').press('Enter')
  await expect(page.getByRole('heading', { name: 'Pilot run' })).toBeVisible()

  await page.goto('/settings')
  const all = await downloadText(page, () => page.getByRole('button', { name: 'Export all my data (JSON)' }).click())
  const j = JSON.parse(all.text)
  expect(j.projects.map((p: { name: string; dataset: unknown[] }) => [p.name, p.dataset.length])).toEqual([['Pilot run', 3]])
  expect(all.text).not.toMatch(/auth-token|access_token|password|apikey/i)

  await page.goto('/app')
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete dataset' }).click()
  await expect(page.getByRole('heading', { name: 'Pilot run' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.getByRole('heading', { name: 'Pilot run' })).toBeVisible()
  await expect.poll(async () => Object.values((await stored(page)).data)[0]?.length).toBe(3)
  await page.goto(base)
  await expect(kpi(page, 'Episodes')).toHaveText('3')
})

