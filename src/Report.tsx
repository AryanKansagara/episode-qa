import { useEffect } from 'react'
import { balance, operatorFeedback, scoreHistogram } from './engine/analyze.ts'
import { describeRule } from './engine/curate.ts'
import { fmtS, useDerived, useProject } from './projectData.ts'
import type { Project } from './store.ts'
import { Empty, fmtPct, Link } from './ui.tsx'
import { KIND_LABEL, KINDS } from './Viewer.tsx'

export default function Report({ id, sheet }: { id: string; sheet?: string }) {
  const { loading, project } = useProject(id)
  if (loading) return <div className="boot" role="status"><span className="spinner" /> Building the report</div>
  if (!project || !project.stats.length) return <section className="page narrow center"><Empty title="Nothing to report"><Link href={`/app${project ? `/p/${id}/data` : ''}`} className="btn primary">Import episodes</Link></Empty></section>
  return <Body project={project} feedback={sheet === 'feedback'} />
}

function Body({ project, feedback }: { project: Project; feedback: boolean }) {
  const d = useDerived(project)
  useEffect(() => { document.title = `${feedback ? 'Operator feedback' : 'Data quality report'} · ${project.name}` }, [feedback, project.name])
  const { stats, keep, decisions, ops } = d
  const n = stats.length
  const date = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const actions = (
    <div className="report-actions">
      <Link href={`/app/p/${project.id}`} className="btn ghost">Back</Link>
      <Link href={`/app/p/${project.id}/${feedback ? 'report' : 'feedback'}`} className="btn outline">{feedback ? 'Quality report' : 'Operator feedback'}</Link>
      <button type="button" className="btn primary" onClick={() => print()}>Print or save PDF</button>
    </div>
  )

  if (feedback) return (
    <article className="report">
      {actions}
      <div className="eyebrow">Operator feedback · {date}</div>
      <h1>{project.name}</h1>
      <p className="muted">One section per operator. Notes appear only where someone is clearly outside the team&rsquo;s norm, so a short list is a good list.</p>
      {ops.map(o => {
        const mine = stats.filter(s => s.operator === o.operator)
        const worst = [...mine].sort((a, b) => a.score - b.score).slice(0, 3)
        return (
          <section key={o.operator} className="sheet">
            <h2>{o.operator}</h2>
            <div className="kpis">
              <div className="kpi"><small>Quality score</small><b>{o.meanScore.toFixed(0)}</b></div>
              <div className="kpi"><small>Episodes</small><b>{o.episodes}</b><p>{fmtS(o.hours * 3600)}</p></div>
              <div className="kpi"><small>Success</small><b>{fmtPct(o.successRate)}</b></div>
              <div className="kpi"><small>Kept for training</small><b>{mine.filter(s => keep.has(s.id)).length}</b></div>
            </div>
            <ul className="feedback">{operatorFeedback(o, ops).map(t => <li key={t}>{t}</li>)}</ul>
            <p className="small"><strong>Episodes to review together:</strong> {worst.map(s => `${s.id} (score ${s.score}${s.issues[0] ? `, ${s.issues[0].msg.toLowerCase()} at ${s.issues[0].t.toFixed(1)} s` : ''})`).join('; ')}</p>
          </section>
        )
      })}
      <p className="muted small">Generated by Episode QA. {project.sampleId ? 'Synthetic sample data.' : ''}</p>
    </article>
  )

  const hist = scoreHistogram(stats)
  const kept = decisions.filter(x => x.include)
  const keptSec = kept.reduce((a, x) => a + (x.trim ? x.trim[1] - x.trim[0] : stats.find(s => s.id === x.id)!.duration), 0)
  const tasks = balance(stats, keep, 'task')
  return (
    <article className="report">
      {actions}
      <div className="eyebrow">Data quality report · {date}</div>
      <h1>{project.name}</h1>
      {project.sampleId && <p className="muted small">Synthetic sample data.</p>}
      <div className="kpis">
        <div className="kpi"><small>Episodes</small><b>{n}</b><p>{fmtS(stats.reduce((a, s) => a + s.duration, 0))} recorded</p></div>
        <div className="kpi"><small>Mean score</small><b>{(stats.reduce((a, s) => a + s.score, 0) / n).toFixed(0)}</b><p>{hist.slice(0, 7).reduce((a, b) => a + b, 0)} below 70</p></div>
        <div className="kpi"><small>Kept</small><b>{kept.length}</b><p>{fmtS(keptSec)} after trims</p></div>
        <div className="kpi"><small>Operators</small><b>{ops.length}</b><p>{tasks.length} tasks</p></div>
      </div>
      <h2>Findings</h2>
      <table><thead><tr><th>Check</th><th className="num">Episodes flagged</th><th className="num">Share</th></tr></thead>
        <tbody>{KINDS.map(k => { const c = stats.filter(s => s.issues.some(i => i.kind === k)).length; return <tr key={k}><td>{KIND_LABEL[k]}</td><td className="num">{c}</td><td className="num">{fmtPct(c / n)}</td></tr> })}
          <tr><td>Near-duplicates (extra copies)</td><td className="num">{d.ctx.dupDrop.size}</td><td className="num">{fmtPct(d.ctx.dupDrop.size / n)}</td></tr></tbody></table>
      <h2>Curation rules in force</h2>
      <ol className="small">{project.rules.filter(r => r.enabled).map(r => <li key={r.id}>{describeRule(r)}</li>)}</ol>
      {Object.keys(project.overrides).length > 0 && <p className="small">Manual overrides: {Object.entries(project.overrides).map(([k, v]) => `${k} (${v})`).join(', ')}</p>}
      <h2>Task balance of the kept set</h2>
      <table><thead><tr><th>Task</th><th className="num">Recorded</th><th className="num">Kept</th><th className="num">Share kept</th><th /></tr></thead>
        <tbody>{tasks.map(r => <tr key={r.key}><td>{r.key}</td><td className="num">{r.episodes}</td><td className="num">{r.kept}</td><td className="num">{fmtPct(r.keptShare)}</td><td>{r.flag === 'under' ? 'Under-represented' : r.flag === 'over' ? 'Over-represented' : ''}</td></tr>)}</tbody></table>
      <h2>Operators</h2>
      <table><thead><tr><th>Operator</th><th className="num">Episodes</th><th className="num">Score</th><th className="num">Success</th><th className="num">Failed grasps</th><th className="num">Idle</th></tr></thead>
        <tbody>{ops.map(o => <tr key={o.operator}><td>{o.operator}</td><td className="num">{o.episodes}</td><td className="num">{o.meanScore.toFixed(0)}</td><td className="num">{fmtPct(o.successRate)}</td><td className="num">{fmtPct(o.failedGraspRate)}</td><td className="num">{fmtPct(o.idleFrac)}</td></tr>)}</tbody></table>
      <h2>Excluded episodes</h2>
      <table className="small"><thead><tr><th>Episode</th><th>Operator</th><th className="num">Score</th><th>Reason</th></tr></thead>
        <tbody>{decisions.filter(x => !x.include).map(x => { const s = stats.find(y => y.id === x.id)!; return <tr key={x.id}><td className="mono">{x.id}</td><td>{s.operator}</td><td className="num">{s.score}</td><td>{x.reasons.join('; ').replace(/Exclude episodes where /g, '')}</td></tr> })}</tbody></table>
      <p className="muted small" style={{ marginTop: 24 }}>Thresholds: drop gap {project.config.th.dropFactor}× period, camera offset {project.config.th.offsetWarnMs} ms, jerk {project.config.th.jerkLimit} rad/s³, idle below {project.config.th.idleSpeed} rad/s for {project.config.th.idleMinSec} s, empty grip {project.config.th.emptyGrip}, duplicate distance {project.config.th.dupDist} m.</p>
    </article>
  )
}
